"""Non-interactive equivalent of selection 1 from eb_modules_v3.py."""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import uuid
from pathlib import Path

from binstar_client.utils import get_server_api


ALLOWED_CHANNELS = ("bioconda", "conda-forge")
PACKAGE_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$")
VERSION_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.+-]{0,127}$")


def write_json(path: Path, payload: dict) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    temporary.replace(path)


def load_request(path: Path) -> dict:
    request = json.loads(path.read_text())

    required = {"request_id", "name", "version", "channel"}
    missing = sorted(required.difference(request))
    if missing:
        raise ValueError(f"Missing request fields: {', '.join(missing)}")

    request_id = str(uuid.UUID(str(request["request_id"])))
    if request_id != path.parent.name.lower():
        raise ValueError("Request UUID does not match its request directory")

    name = str(request["name"]).strip()
    if not PACKAGE_PATTERN.fullmatch(name):
        raise ValueError("Invalid Conda package name")

    channel = str(request["channel"]).strip().lower()
    if channel not in ALLOWED_CHANNELS:
        raise ValueError("Channel is not approved")

    version = str(request.get("version") or "latest").strip()
    if version.casefold() != "latest" and not VERSION_PATTERN.fullmatch(version):
        raise ValueError("Invalid Conda package version")

    return {
        "request_id": request_id,
        "name": name,
        "channel": channel,
        "version": version,
    }


def resolve_package(request: dict) -> dict:
    api = get_server_api()
    package_data = api.package(request["channel"], request["name"])
    available_versions = {str(item) for item in package_data.get("versions", [])}

    if request["version"].casefold() == "latest":
        version = str(package_data["latest_version"])
    else:
        version = request["version"]
        if version not in available_versions:
            raise ValueError(
                f"Version {version!r} is not present in "
                f"{request['channel']}/{request['name']}"
            )

    return {
        **request,
        "version": version,
        "homepage": f"https://anaconda.org/{request['channel']}/{request['name']}",
        "description": str(package_data.get("summary") or request["name"]),
    }


def render_easyconfig(package: dict) -> str:
    if package["channel"] == "bioconda":
        channels = ["bioconda", "conda-forge"]
    else:
        channels = ["conda-forge"]

    return f'''##
# Generated by the Gencore package automation service.
##

easyblock = 'Conda'

name = {package["name"]!r}
version = {package["version"]!r}

homepage = {package["homepage"]!r}
description = {package["description"]!r}

toolchain = SYSTEM

requirements = "%(name)s=%(version)s"
channels = {channels!r}

builddependencies = [('Mamba', '23.11.0-0')]

sanity_check_paths = {{}}

moduleclass = 'tools'
'''


def run_build(request_path: Path) -> int:
    result_path = request_path.parent / "result.json"
    easybuild_prefix = os.environ.get("EASYBUILD_PREFIX", "/scratch/gencore/.eb/3.0")

    try:
        request = load_request(request_path)
        package = resolve_package(request)

        easyconfig_dir = request_path.parent / "eb_config"
        easyconfig_dir.mkdir(mode=0o750, exist_ok=True)
        easyconfig_path = easyconfig_dir / f'{package["name"]}-{package["version"]}.eb'
        easyconfig_path.write_text(render_easyconfig(package))

        write_json(
            result_path,
            {
                **package,
                "status": "building",
                "easyconfig": str(easyconfig_path),
                "easybuild_prefix": easybuild_prefix,
            },
        )

        completed = subprocess.run(
            [
                "eb",
                "--modules-tool=EnvironmentModules",
                "--disable-modules-tool-version-check",
                "--logtostdout",
                f"--prefix={easybuild_prefix}",
                "-r",
                str(easyconfig_path),
            ],
            cwd=request_path.parent,
            check=False,
        )
        if completed.returncode != 0:
            raise RuntimeError(f"EasyBuild exited with status {completed.returncode}")

        write_json(
            result_path,
            {
                **package,
                "status": "completed",
                "easyconfig": str(easyconfig_path),
                "easybuild_prefix": easybuild_prefix,
                "module_load_commands": [
                    "module load all gencore/3",
                    f'module load {package["name"]}/{package["version"]}',
                ],
            },
        )
        print(f'GENCORE_BUILD_COMPLETED {package["name"]}/{package["version"]}')
        return 0
    except Exception as error:
        write_json(
            result_path,
            {
                "status": "failed",
                "error": str(error)[:2000],
            },
        )
        print(f"GENCORE_BUILD_FAILED {error}", file=sys.stderr)
        return 1


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--request", required=True, type=Path)
    arguments = parser.parse_args()
    return run_build(arguments.request.resolve())


if __name__ == "__main__":
    raise SystemExit(main())
